  `image_path` VARCHAR(255) NULL,
  `image_webp_path` VARCHAR(255) NULL,
  `poster_path` VARCHAR(255) NULL,
  `poster_webp_path` VARCHAR(255) NULL,
  `video_720_path` VARCHAR(255) NULL,
  `video_480_path` VARCHAR(255) NULL,
  `brand` VARCHAR(190) NULL,
  `title_html` VARCHAR(500) NULL,
  `body` TEXT NULL,
  `body_sub` TEXT NULL,
  `cta1_label` VARCHAR(120) NULL,
  `cta1_url` VARCHAR(255) NULL,
  `cta1_style` VARCHAR(32) NULL DEFAULT 'primary',
