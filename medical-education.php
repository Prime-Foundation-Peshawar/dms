          <h2 class="sec-title" style="font-size:1.8rem;">Medical Education</h2>
          <p style="font-family:var(--font-body);font-size:.95rem;color:var(--gray-dark);line-height:1.85;">The
            education system is designed to train students on application of knowledge of basic sciences to clinical
            problems, use computers and IT in line with currents trends of medical education and achieve professional
            and ethical excellence at end of education in medical college.</p>
          <p style="font-family:var(--font-body);font-size:.95rem;color:var(--gray-dark);line-height:1.85;">The
            education system and curriculum is designed to meet the challenges of contemporary global health needs and
            based on <strong>integrated teaching system</strong>. It also incorporate the preliminary application
            of knowledge of basic sciences to clinical problems from first professional. Students are given the
            opportunities of exposure to "real-life" clinical problems relevant to their level of knowledge.</p>
          <p style="font-family:var(--font-body);font-size:.95rem;color:var(--gray-dark);line-height:1.85;">Use of
            computers and IT is a part of the teaching and students are taught the relevant computers softwares
            from first year. The college self-learning resource center is open for use to students and teachers
            where they are provided with "hands-on" assistance and training.</p>
          <p style="font-family:var(--font-body);font-size:.95rem;color:var(--gray-dark);line-height:1.85;">Internal
            assessment will be an integral part of evaluation system and part of it will be computer-based evaluation,
            on subjects already taught to them.</p>
          <p style="font-family:var(--font-body);font-size:.95rem;color:var(--gray-dark);line-height:1.85;">Students
            are given the opportunity of training on research methodologies and paper writing. They are expected
            to produce at least <strong>five research papers in five years</strong> and are encouraged to submit
            their papers to the national and international conferences. College sponsors all expenses involved in
            presentation of papers accepted in various national conferences.</p>
          <p style="font-family:var(--font-body);font-size:.95rem;color:var(--gray-dark);line-height:1.85;">Teacher and
            students are engaged in regular dialogue through tutorial system and accessibility of teachers to
            students are facilitated to develop a better teacher students relation based on respect and professional
            freedom.</p>
          <p style="font-family:var(--font-body);font-size:.95rem;color:var(--gray-dark);line-height:1.85;">We are
            committed to achieve our goal, establish and maintain our standards, through self-accountability, monitoring
            and continuous evaluation. All available education standards outlined by professional bodies like PMDC, CPSP
            and HEC for imparting medical education will be followed in letter and spirit to achieve this goal.</p>

