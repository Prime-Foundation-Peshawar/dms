          <h5
            style="font-family:var(--font-head);font-size:1.3rem;color:var(--navy);margin-top:30px;margin-bottom:16px;">
            Structure of the Programme and Curriculum</h5>
          <p style="font-family:var(--font-body);font-size:.92rem;color:var(--gray-dark);line-height:1.85;">Postgraduate
            medical education (PGME) programmes at PMC, strive to produce specialist doctors that demonstrate excellence
            in professional skills, knowledge and ethical behaviour across various health care settings. Experienced,
            qualified supervisors with exemplary professional reputation are the central pillar of the postgraduate
            medical education at Riphah International University - Peshawar Campus. Our well-equipped training environment with a variety of case mix provide the
            necessary experiential learning for the postgraduate trainee (PGT). A well-established quality enhancement
            cell with qualified staff and IT support serves to strengthen the quality assurance mechanism designed for
            continuous improvement of PGME.</p>
          <p style="font-family:var(--font-body);font-size:.92rem;color:var(--gray-dark);line-height:1.85;">Riphah International University - Peshawar Campus strives
            to establish a culture of research and evidence-based practice for the undergraduate and postgraduate
            medical education. These educational interventions are supported by well-established department of
            undergraduate medical research (UMR) and office of research, innovation and commercialization (ORIC).</p>
          <p style="font-family:var(--font-body);font-size:.92rem;color:var(--gray-dark);line-height:1.85;">In the
