          <p style="font-family:var(--font-body);font-size:.92rem;color:var(--gray-dark);line-height:1.85;">The model
            organizes postgraduate training around eight core competencies centered at patient and population care.
            These are visually depicted in the given diagram as an "inner" and "outer" circles, signifying integrated
            clinical and holistic professional development of the PGT. The inner circle represents five core
            competencies that shape patient care and the outer circle depicts three meta- competencies which contribute
            to the professional identity formation of the trainee. Each of these competencies guide several learning
            outcomes as prescribed by the CPSP in their curriculum document and reproduced in the following section.</p>

